#!/usr/bin/env python3
"""
Copy one generated .sv into orfs_designs/ and write ASAP7 config.mk + constraint.sdc.

Usage (repo root):
  python3 scripts/prepare_orfs_design.py generated/openfloat/FP_add_32_1.sv
  python3 scripts/prepare_orfs_design.py generated/hardfloat/FPADD_8_24.sv --period 2000
"""

from __future__ import annotations

import argparse
import os
import sys

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.abspath(os.path.join(SCRIPT_DIR, ".."))
sys.path.insert(0, SCRIPT_DIR)

from estimate import get_top_module, preprocess_sv_file  # noqa: E402
from fp_design_meta import design_id, detect_clock_reset, parse_generated_sv  # noqa: E402


CONFIG_MK = """# Generated by scripts/prepare_orfs_design.py — do not edit by hand.
export PLATFORM = asap7
export DESIGN_NICKNAME = {nickname}
export DESIGN_NAME = {top}

# docker_shell mounts the eval repo at /work. Local runs pass OPENHWFP_ROOT on the make command line.
OPENHWFP_ROOT ?= /work

export VERILOG_FILES = $(OPENHWFP_ROOT)/orfs_designs/src/{nickname}/{sv_name}
export SDC_FILE = $(OPENHWFP_ROOT)/orfs_designs/asap7/{nickname}/constraint.sdc

export SYNTH_HDL_FRONTEND = slang
export CORE_UTILIZATION = 40
export CORE_ASPECT_RATIO = 1
export CORE_MARGIN = 2
export PLACE_DENSITY = 0.45
export TNS_END_PERCENT = 100
"""

CONSTRAINT_SDC = """current_design {top}

set clk_name core_clock
set clk_port_name {clock_port}
set clk_period {period}
set clk_io_pct 0.2

set clk_port [get_ports $clk_port_name]
create_clock -name $clk_name -period $clk_period $clk_port

set non_clock_inputs [lsearch -inline -all -not -exact [all_inputs] $clk_port]
set_input_delay  [expr $clk_period * $clk_io_pct] -clock $clk_name $non_clock_inputs
set_output_delay [expr $clk_period * $clk_io_pct] -clock $clk_name [all_outputs]
"""


def nickname_for(meta: dict) -> str:
    lib = meta.get("library") or "lib"
    stem = meta.get("stem") or "design"
    return f"{lib}_{stem}".replace("-", "_")


def main() -> int:
    ap = argparse.ArgumentParser(description="Prepare one SV module for ORFS ASAP7")
    ap.add_argument("sv", help="Path to generated .sv (e.g. generated/openfloat/FP_add_32_1.sv)")
    ap.add_argument("--period", type=float, default=2000.0, help="Clock period in ASAP7 units (ps). Default 2000.")
    ap.add_argument("--nickname", default=None)
    args = ap.parse_args()

    os.chdir(REPO_ROOT)
    sv_path = args.sv
    if not os.path.exists(sv_path):
        print(f"ERROR: {sv_path} not found. Run bash scripts/run_ppa_estimation.sh first.", file=sys.stderr)
        return 1

    meta = parse_generated_sv(sv_path)
    top = get_top_module(sv_path)
    nickname = args.nickname or nickname_for(meta)

    raw = open(sv_path, "r", encoding="utf-8", errors="ignore").read()
    ports = detect_clock_reset(raw)
    clock_port = ports["clock_port"] or "clock"
    if ports["clock_port"] is None:
        print(f"WARNING: no clock port detected; SDC will use '{clock_port}'")

    pre = preprocess_sv_file(sv_path)
    sv_name = os.path.basename(sv_path)
    src_dir = os.path.join("orfs_designs", "src", nickname)
    cfg_dir = os.path.join("orfs_designs", "asap7", nickname)
    os.makedirs(src_dir, exist_ok=True)
    os.makedirs(cfg_dir, exist_ok=True)

    out_sv = os.path.join(src_dir, sv_name)
    with open(out_sv, "w", encoding="utf-8") as f:
        f.write(pre if pre is not None else raw)

    with open(os.path.join(cfg_dir, "config.mk"), "w", encoding="utf-8") as f:
        f.write(CONFIG_MK.format(nickname=nickname, top=top, sv_name=sv_name))
    with open(os.path.join(cfg_dir, "constraint.sdc"), "w", encoding="utf-8") as f:
        f.write(CONSTRAINT_SDC.format(top=top, clock_port=clock_port, period=args.period))

    meta_path = os.path.join(cfg_dir, "design_meta.json")
    import json
    with open(meta_path, "w", encoding="utf-8") as f:
        json.dump(
            {
                **meta,
                "design_id": design_id(meta),
                "design_name": top,
                "nickname": nickname,
                "clock_port": clock_port,
                "reset_port": ports["reset_port"],
                "clock_period_ps": args.period,
                "platform": "asap7",
                "prepared_sv": out_sv.replace("\\", "/"),
            },
            f,
            indent=2,
        )

    print(f"Prepared ORFS design '{nickname}'")
    print(f"  top={top} clock={clock_port} period={args.period}ps")
    print(f"  {out_sv}")
    print(f"  {cfg_dir}/config.mk")
    print(f"Next: bash scripts/run_openroad_design.sh {nickname}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
