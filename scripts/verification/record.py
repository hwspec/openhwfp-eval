"""The verification record. This is the actual deliverable, not the pass/fail line.

Fields mirror Table 2 of the paper: reference model, vector counts, special-case coverage,
mismatch detail, ULP summary. A row is only comparable to another row when their profiles and
conformance levels match, so both travel with the result.
"""

from __future__ import annotations

import datetime
import json
import os
import platform
import subprocess

RESULTS_DIR = "verification_results"


def _git(args, cwd="."):
    try:
        p = subprocess.run(["git"] + args, cwd=cwd, capture_output=True,
                           text=True, timeout=20, check=False)
        return p.stdout.strip() if p.returncode == 0 else None
    except Exception:
        return None


def _reference_version(root="."):
    """Which SoftFloat produced the expected values. Pins the run to a commit."""
    sf = os.path.join(root, "berkeley-softfloat-3")
    tf = os.path.join(root, "berkeley-testfloat-3")
    return {
        "berkeley-softfloat-3": _git(["rev-parse", "HEAD"], sf) if os.path.isdir(sf) else None,
        "berkeley-testfloat-3": _git(["rev-parse", "HEAD"], tf) if os.path.isdir(tf) else None,
    }


def build_record(job, cmp, vectors) -> dict:
    design = job["design"]
    profile = cmp.profile
    categories, omitted = cmp.category_report()

    return {
        "design_id": design["design_id"],
        "library": design["library"],
        "operator": design["operator"],
        "precision": design["format"].get("name"),
        "descriptor_path": design.get("descriptor_path"),

        "status": "pass" if cmp.mismatches == 0 and cmp.checks > 0 else "fail",
        "conformance_level": design["conformance_level"],
        "tier": design["tier"],
        "profile": {
            "rounding_modes": profile.rounding_modes,
            "rounding_control": profile.rounding_control,
            "exception_flags": profile.exception_flags,
            "subnormals": profile.subnormals,
            "nan_payload": profile.nan_payload,
            "signed_zero": profile.signed_zero,
            "ulp_budget": profile.ulp_budget,
            "not_evaluated_reason": profile.not_evaluated_reason,
        },

        # Spelled out rather than left as a bare tier number, so a record explains itself
        # without the schema next to it.
        "reference": {
            "tier": design["tier"],
            "kind": "exact" if design["tier"] == 1 else "bounded",
            "model": "berkeley-softfloat-3" if design["tier"] == 1 else "mpfr",
            "model_role": (
                "correctly rounded result and IEEE exception flags, generated by testfloat_gen"
                if design["tier"] == 1 else
                "high-precision evaluation rounded to the target format"),
            "version": _reference_version(),
            "comparison": "bit_exact" if design["tier"] == 1 else "ulp_bounded",
            "ulp_budget": profile.ulp_budget,
        },
        "reference_model": "berkeley-softfloat-3" if design["tier"] == 1 else "mpfr",
        "reference_version": _reference_version(),
        "flag_check": profile.flag_check,

        "rounding_mode": job["rounding"],
        "tininess": job["tininess"],

        "vectors": {
            "source": "testfloat_gen",
            "function": vectors.function,
            "level": vectors.level,
            "seed": vectors.seed,
            "count": vectors.count,
            "truncated_from": vectors.truncated_from,
            "sha256": vectors.sha256,
            "path": os.path.relpath(vectors.path),
        },
        "directed_tests": vectors.count,
        "random_tests": 0,
        "checks_performed": cmp.checks,
        "vectors_excluded_by_profile": cmp.excluded,
        "exclusion_reasons": dict(sorted(cmp.exclusions.items())),
        "mismatch_count": cmp.mismatches,
        # Grouped by failure shape with one exemplar each. Listing every failing vector would
        # bloat the corpus without teaching anything a count does not.
        "mismatch_categories": categories,
        "mismatch_categories_without_exemplar": omitted,
        "special_case_coverage": dict(sorted(cmp.coverage.items())),
        "max_ulp": cmp.max_ulp,
        "mean_ulp": cmp.mean_ulp,
        "ulp_histogram": dict(sorted(cmp.ulp_histogram.items())),
        "canary_ok": getattr(cmp, "canary_ok", False),

        "environment": {
            "host": platform.node(),
            "timestamp": datetime.datetime.now(datetime.timezone.utc).isoformat(),
        },
    }


def result_path(job) -> str:
    design = job["design"]["design_id"].replace("/", "__")
    return os.path.join(
        RESULTS_DIR, f"{design}__{job['rounding']}__{job['tininess']}.json")


def write_result(job, cmp, vectors) -> str:
    rec = build_record(job, cmp, vectors)
    path = job.get("result_path") or result_path(job)
    os.makedirs(os.path.dirname(path), exist_ok=True)
    with open(path, "w") as fh:
        json.dump(rec, fh, indent=2)
        fh.write("\n")
    return path
